#requires -Version 5.1
<# 创建带"错过补跑"(StartWhenAvailable) 的 Windows 计划任务。可选 -MaxDelayHours 限定补跑窗口（防陈旧任务突袭 + 内置防重复）。 #>
[CmdletBinding()]
param(
  [Parameter(Mandatory)][string]$Name,
  [Parameter(Mandatory)][string]$Run,
  [string]$Arguments = '',
  [string]$WorkingDirectory = '',
  [string]$Description = '',
  [ValidatePattern('^\d{1,2}:\d{2}$')][string]$Daily = '',
  [ValidateSet('Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday')][string[]]$Weekly = @(),
  [ValidatePattern('^\d{1,2}:\d{2}$')][string]$WeeklyAt = '',
  [ValidateRange(1, 168)][int]$Hourly = 0,
  [ValidateRange(0, 8760)][int]$MaxDelayHours = 24,
  [switch]$AtLogon,
  [switch]$AtStartup,
  [switch]$Wake,
  [switch]$Force
)
$ErrorActionPreference = 'Stop'

$identity = [Security.Principal.WindowsIdentity]::GetCurrent().Name

# --- 前置校验：全部在写任何文件之前 ---
if ($AtStartup) {
  $wp = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
  if (-not $wp.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw '-AtStartup (boot trigger) requires an elevated (administrator) PowerShell session. Run as admin, or use -AtLogon instead.'
  }
}
if ($Weekly -and -not $WeeklyAt) { throw 'Weekly trigger needs -WeeklyAt "HH:mm"' }
# 默认补跑窗口 24 小时（一天）；0 = 不限时长、总是补最近一次
$windowExplicit = $PSBoundParameters.ContainsKey('MaxDelayHours')
if ($windowExplicit -and $MaxDelayHours -gt 0) {
  if ($Hourly -gt 0) { throw '-MaxDelayHours does not support -Hourly (the window anchor would differ from the trigger anchor).' }
  if ($AtLogon -or $AtStartup) { throw '-MaxDelayHours only applies to time-based triggers (-Daily / -Weekly).' }
}
$useWindow = (($Daily -or $Weekly) -and $MaxDelayHours -gt 0)

$triggers = @()
if ($Daily)   { $triggers += New-ScheduledTaskTrigger -Daily -At $Daily }
if ($Weekly)  { $triggers += New-ScheduledTaskTrigger -Weekly -DaysOfWeek $Weekly -At $WeeklyAt }
if ($Hourly -gt 0) { $triggers += New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Hours $Hourly) }
if ($AtLogon)  { $triggers += New-ScheduledTaskTrigger -AtLogOn -User $identity }
if ($AtStartup){ $triggers += New-ScheduledTaskTrigger -AtStartup }
if (-not $triggers) { throw 'Need a trigger: -Daily / -Weekly+-WeeklyAt / -Hourly / -AtLogon / -AtStartup' }

$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -MultipleInstances IgnoreNew -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
if ($Wake) { $settings.WakeToRun = $true }
$principal = New-ScheduledTaskPrincipal -UserId $identity -LogonType Interactive -RunLevel Limited

if ($useWindow) {
  # 窗口模式：生成守卫脚本（窗口判断 + .last 状态防重复），payload 经 ProcessStartInfo 原样传参，不经 PS 二次解析
  $jobsDir = Join-Path $env:USERPROFILE 'catchup-jobs'
  New-Item -ItemType Directory -Force -Path $jobsDir | Out-Null
  $safeName = $Name -replace '[\\/:*?"''<>|]', '_'
  $guardPath = Join-Path $jobsDir "$safeName.guard.ps1"

  $runLit = "'" + ($Run -replace "'", "''") + "'"
  $weeklyExpr = if ($Weekly.Count) { "@('" + ($Weekly -join "','") + "')" } else { '@()' }

  $argsLine = ''
  if ($Arguments) { $argsLine = '  $psi.Arguments = ' + "'" + ($Arguments -replace "'", "''") + "'" }
  $wdLine = ''
  if ($WorkingDirectory) { $wdLine = '  $psi.WorkingDirectory = ' + "'" + ($WorkingDirectory -replace "'", "''") + "'" }

  $guardBody = @'
# generated by New-CatchupTask.ps1 for task '__TASKNAME__' - do not edit by hand
$now = Get-Date
$MaxDelayHours = __DELAY__
$lastFile = Join-Path $PSScriptRoot '__SAFENAME__.last'
$prev = [datetime]::MinValue
if (Test-Path $lastFile) {
  try { $prev = [datetime]::ParseExact((Get-Content $lastFile -Raw).Trim(), 'o', [Globalization.CultureInfo]::InvariantCulture) } catch { $prev = [datetime]::MinValue }
}
$occ = $null
if ('__DAILY__' -ne '') {
  $t = [datetime]'__DAILY__'
  $occ = $now.Date.AddHours($t.Hour).AddMinutes($t.Minute)
  if ($now -lt $occ) { $occ = $occ.AddDays(-1) }
} else {
  $want = __WEEKLY__
  $wt = [datetime]'__WEEKLYAT__'
  for ($i = 0; $i -le 7; $i++) {
    $d = $now.Date.AddDays(-$i)
    $o = $d.AddHours($wt.Hour).AddMinutes($wt.Minute)
    if (($want -contains $d.DayOfWeek.ToString()) -and ($o -le $now)) { $occ = $o; break }
  }
}
if ($null -eq $occ) { Write-Output 'catchup-guard: no past occurrence matched, skip'; exit 0 }
if ($occ -le $prev) { Write-Output 'catchup-guard: already ran for this occurrence, skip'; exit 0 }
$delayH = ($now - $occ).TotalHours
if ($MaxDelayHours -gt 0 -and $delayH -gt $MaxDelayHours) {
  Write-Output ('catchup-guard: SKIP, stale by {0:N1}h (window {1}h)' -f $delayH, $MaxDelayHours)
  exit 0
}
Write-Output ('catchup-guard: within window ({0:N1}h), running payload' -f $delayH)
try {
  $psi = New-Object System.Diagnostics.ProcessStartInfo
  $psi.FileName = __RUN__
__ARGSLINE__
__WDLINE__
  $psi.UseShellExecute = $false
  $psi.CreateNoWindow = $true
  $p = [System.Diagnostics.Process]::Start($psi)
  $p.WaitForExit()
  $code = $p.ExitCode
} catch {
  Write-Output ('catchup-guard: payload failed to start: {0}' -f $_.Exception.Message)
  exit 1
}
if ($code -eq 0) { Set-Content -Path $lastFile -Value $occ.ToString('o') }
exit $code
'@
  $guardBody = $guardBody.Replace('__TASKNAME__', ($Name -replace "'", "''")).Replace('__DELAY__', [string]$MaxDelayHours).Replace('__SAFENAME__', $safeName).Replace('__DAILY__', $Daily).Replace('__WEEKLY__', $weeklyExpr).Replace('__WEEKLYAT__', $(if ($WeeklyAt) { $WeeklyAt } else { '00:00' })).Replace('__RUN__', $runLit).Replace('__ARGSLINE__', $argsLine).Replace('__WDLINE__', $wdLine)
  Set-Content -Path $guardPath -Value $guardBody -Encoding UTF8

  $actionParams = @{ Execute = 'powershell.exe'; Argument = "-NoProfile -ExecutionPolicy Bypass -File `"$guardPath`"" }
  if ($WorkingDirectory) { $actionParams.WorkingDirectory = $WorkingDirectory }
  $action = New-ScheduledTaskAction @actionParams
  "Window mode: guard script at $guardPath"
} else {
  $actionParams = @{ Execute = $Run }
  if ($Arguments)        { $actionParams.Argument = $Arguments }
  if ($WorkingDirectory) { $actionParams.WorkingDirectory = $WorkingDirectory }
  $action = New-ScheduledTaskAction @actionParams
}

$registerParams = @{
  TaskName = $Name; Action = $action; Trigger = $triggers
  Settings = $settings; Principal = $principal; Force = $Force.IsPresent
}
if ($Description) { $registerParams.Description = $Description }
try {
  Register-ScheduledTask @registerParams -ErrorAction Stop | Out-Null
} catch {
  if ($useWindow -and (Test-Path $guardPath)) { Remove-Item $guardPath -ErrorAction SilentlyContinue }
  throw "Register-ScheduledTask failed for '$Name': $($_.Exception.Message)"
}

$t = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
if (-not $t) { throw "Task '$Name' not found after registration - registration silently failed." }
"Created '$Name'. StartWhenAvailable=$($t.Settings.StartWhenAvailable)"
